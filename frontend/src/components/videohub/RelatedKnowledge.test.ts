import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import test from 'node:test'

test('related knowledge is list-first, keeps the native Wiki graph, and reads pages in a drawer', () => {
  const relatedKnowledge = readFileSync(new URL('./RelatedKnowledge.vue', import.meta.url), 'utf8')

  assert.match(relatedKnowledge, /fetchNativeWikiGraph\(context\.value\.videoId\)/)
  assert.match(relatedKnowledge, /fetchNativeWikiRelations\(context\.value\.videoId\)/)
  assert.doesNotMatch(relatedKnowledge, /getWikiGraph\(/)
  assert.match(relatedKnowledge, /getWikiPage\(context\.value\.knowledgeBaseId,\s*slug\)/)
  assert.match(relatedKnowledge, /viewMode = ref<'list' \| 'graph'>\('list'\)/)
  assert.match(relatedKnowledge, /t-drawer/)
  assert.match(relatedKnowledge, /size="560px"/)
  assert.match(relatedKnowledge, /drawer-class-name="related-wiki-drawer"/)
  assert.match(relatedKnowledge, /aria-label="返回关联知识"/)
  assert.match(relatedKnowledge, /@click="drawerOpen = false"/)
  assert.match(relatedKnowledge, /width: 100vw !important/)
  assert.match(relatedKnowledge, /max-width: 100%/)
  assert.match(relatedKnowledge, /v-if="relationsLoading"/)
  assert.match(relatedKnowledge, /暂无足够内容生成可靠的关联说明/)
  assert.doesNotMatch(relatedKnowledge, /本视频摘要引用了该 Wiki 页面/)
  assert.doesNotMatch(relatedKnowledge, /来自 WeKnora Wiki|class="source"/)
  assert.match(relatedKnowledge, /class="overview">\{\{ overviewTitle \}\}/)
  assert.match(relatedKnowledge, /关联 \$\{relatedNodes\.value\.length\} 篇 Wiki 页面/)
  assert.doesNotMatch(relatedKnowledge, /<p class="overview"/)
  assert.match(relatedKnowledge, /symbolSize: node\.slug === center \? 56 : 34/)
  assert.match(relatedKnowledge, /width: 104, overflow: 'truncate'/)
  assert.doesNotMatch(relatedKnowledge, /class="reader markdown-content"/)
  assert.match(relatedKnowledge, /background: rgba\(255,255,255,\.72\)/)
  assert.match(relatedKnowledge, /backdrop-filter: blur\(20px\) saturate\(112%\)/)
  assert.match(relatedKnowledge, /\.reader \{[^}]*font-size: 14px/)
  assert.match(relatedKnowledge, /\.reader :deep\(h1\)[^{]*\{[^}]*font-size: 14px; font-weight: 600/)
  assert.match(relatedKnowledge, /\.t-drawer__body > \* \{[^}]*max-width: 100%/)
  assert.match(relatedKnowledge, /font: var\(--td-font-title-small\); font-weight: 600/)
  assert.doesNotMatch(relatedKnowledge, /KnowledgeAnchorCard|RelationOverviewCard|GraphCanvas|crossVideo/)
})
